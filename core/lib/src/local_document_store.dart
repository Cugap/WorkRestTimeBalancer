import 'dart:async';

/// Порт локального хранилища документа. Ядро не знает, где лежит документ:
/// оболочка реализует порт средствами платформы (в MVP — `shared_preferences`)
/// и не читает и не пишет ничего, кроме строки документа целиком.
///
/// Порты асинхронные, потому что платформенное хранилище асинхронное; чтение
/// одно на запуск приложения, запись — после каждого принятого изменения
/// состояния.
abstract interface class LocalDocumentStore {
  /// Прочитать сохранённый документ; null — сохранённого документа нет.
  Future<String?> read();

  /// Записать документ целиком, заменив прежний.
  Future<void> write(String document);
}
