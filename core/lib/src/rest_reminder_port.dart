import 'rest_reminder.dart';

/// Порт напоминаний о конкретном отдыхе. Ядро решает, о каких отдыхах и когда
/// напоминать, а оболочка только планирует и отменяет их средствами платформы
/// (в MVP — `flutter_local_notifications`).
///
/// Раскладка всегда передаётся целиком: сначала [cancelAll], затем по одному
/// [schedule] для каждой точки. Поэтому порту не нужно уметь изменять уже
/// запланированное напоминание — любая смена состояния заменяет раскладку.
abstract interface class RestReminderPort {
  /// Запланировать напоминание об одном отдыхе.
  Future<void> schedule(RestReminder reminder);

  /// Отменить все запланированные напоминания.
  Future<void> cancelAll();
}
