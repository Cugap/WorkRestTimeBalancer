import 'dart:async';

/// Порт файлового переноса документа между устройствами. Ядро не знает ни о
/// путях, ни о системных диалогах: оболочка реализует порт средствами
/// платформы (в MVP — `file_picker`) и передаёт содержимое файла строкой.
///
/// Порты асинхронные, потому что диалоги платформы асинхронные. Отмена в любом
/// из методов не меняет данные пользователя.
abstract interface class DocumentFileGateway {
  /// Сохранить [contents] в файл под предложенным именем [suggestedName].
  /// Возвращает false, если пользователь отменил сохранение.
  Future<bool> save(String contents, {required String suggestedName});

  /// Прочитать файл, выбранный пользователем. Возвращает null, если выбор
  /// отменён.
  Future<String?> pick();
}
